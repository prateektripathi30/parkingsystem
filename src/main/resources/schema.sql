CREATE TABLE IF NOT EXISTS floors (
    floor_number INT PRIMARY KEY
);

CREATE TABLE IF NOT EXISTS parking_spots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    floor_number INT NOT NULL REFERENCES floors(floor_number),
    spot_number INT NOT NULL,
    spot_type VARCHAR(16) NOT NULL,
    occupied BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_floor_spot UNIQUE (floor_number, spot_number),
    CONSTRAINT ck_spot_type CHECK (spot_type IN ('MOTORCYCLE', 'COMPACT', 'LARGE', 'BUS'))
);

CREATE INDEX IF NOT EXISTS idx_spots_allocation
    ON parking_spots(floor_number, occupied, spot_type, spot_number);

CREATE TABLE IF NOT EXISTS parking_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    license_plate VARCHAR(20) NOT NULL,
    vehicle_type VARCHAR(16) NOT NULL,
    spot_id BIGINT NOT NULL REFERENCES parking_spots(id),
    entry_time_ms BIGINT NOT NULL,
    exit_time_ms BIGINT,
    hourly_rate_cents BIGINT NOT NULL,
    charged_cents BIGINT,
    CONSTRAINT ck_session_time CHECK (exit_time_ms IS NULL OR exit_time_ms >= entry_time_ms),
    CONSTRAINT ck_session_rate CHECK (hourly_rate_cents >= 0),
    CONSTRAINT ck_session_charge CHECK (charged_cents IS NULL OR charged_cents >= 0)
);

CREATE INDEX IF NOT EXISTS idx_sessions_history
    ON parking_sessions(license_plate, entry_time_ms DESC);

CREATE INDEX IF NOT EXISTS idx_sessions_active
    ON parking_sessions(exit_time_ms, entry_time_ms);

CREATE TABLE IF NOT EXISTS active_vehicles (
    license_plate VARCHAR(20) PRIMARY KEY,
    session_id BIGINT NOT NULL UNIQUE REFERENCES parking_sessions(id)
);
